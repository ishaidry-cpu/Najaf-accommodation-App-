/**
 * Packs a built Worker's static assets into the Worker bundle itself, for deploying from a Claude Code cloud
 * session.
 *
 * Why: Cloudflare uploads static assets in two steps. The asset upload session is opened with the account's API
 * key, but the files themselves must be sent with the short-lived upload token Cloudflare returns. In a cloud
 * session the HTTPS proxy puts the account's API key on every api.cloudflare.com request, replacing that upload
 * token, so the file upload is refused (401 Unauthorized) whenever a page file has changed. The Worker script
 * upload itself works, so the cloud deploy ships the same files inside the Worker instead.
 *
 * What it changes in the build output (.cloudflare/output/v1/workers/<name>): it writes embedded-assets.js and
 * static-entry.js into the bundle, makes static-entry.js the main module, and removes the `assets` setting.
 * static-entry.js serves the files the way the assets setting did: routes in runWorkerFirst (/api/*) go to the
 * app's Worker; other paths get the matching file, "/" and page routes get index.html (single-page app);
 * hashed build files are cached for a year, everything else is revalidated. Deploying from a computer without
 * the proxy keeps using Cloudflare's static assets.
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png',
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8', '.woff': 'font/woff', '.woff2': 'font/woff2', '.webmanifest': 'application/manifest+json',
  '.map': 'application/json',
};
const TEXT = /^(text\/|application\/(json|manifest\+json)|image\/svg)/;

function walk(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push('/' + path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/** Rewrites one Worker's build output in place. Returns what it packed. */
export function embedAssets(workerDir) {
  const configPath = path.join(workerDir, 'worker.config.json');
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const assetsDir = path.join(workerDir, 'assets');
  if (!config.assets) return { embedded: 0, bytes: 0, skipped: 'no assets setting' };
  if (!existsSync(assetsDir)) throw new Error(`No assets directory at ${assetsDir}`);
  const bundle = path.join(workerDir, 'bundle');
  const main = config.manifest?.mainModule || 'index.js';
  if (main === 'static-entry.js') throw new Error('Assets are already embedded in this build output.');

  const blobs = {};
  const files = {};
  let bytes = 0;
  for (const route of walk(assetsDir)) {
    const data = readFileSync(path.join(assetsDir, ...route.slice(1).split('/')));
    const type = TYPES[path.extname(route).toLowerCase()] || 'application/octet-stream';
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 20);
    if (!blobs[hash]) {
      blobs[hash] = TEXT.test(type) ? { text: data.toString('utf8') } : { base64: data.toString('base64') };
      bytes += data.length;
    }
    // Vite puts content-hashed build files under /assets/; they never change, so browsers may keep them.
    const immutable = /^\/assets\/.+-[A-Za-z0-9_-]{8,}\.[a-z0-9]+$/.test(route);
    files[route] = { blob: hash, type, etag: `"${hash}"`, cache: immutable ? 'public, max-age=31536000, immutable' : 'public, max-age=0, must-revalidate' };
  }
  const settings = {
    spa: config.assets.notFoundHandling === 'single-page-application',
    workerFirst: config.assets.runWorkerFirst || [],
  };
  writeFileSync(path.join(bundle, 'embedded-assets.js'),
    `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const blobs = ${JSON.stringify(blobs)};\nexport const files = ${JSON.stringify(files)};\nexport const settings = ${JSON.stringify(settings)};\n`);
  writeFileSync(path.join(bundle, 'static-entry.js'), entrySource(main));
  delete config.assets;
  config.manifest = { ...(config.manifest || { type: 'partial', modules: {} }), mainModule: 'static-entry.js' };
  writeFileSync(configPath, JSON.stringify(config));
  // cf deploy uploads an `assets` folder it finds beside the bundle; moved aside, nothing goes to the upload step.
  const aside = path.join(workerDir, 'assets-embedded');
  rmSync(aside, { recursive: true, force: true });
  renameSync(assetsDir, aside);
  return { embedded: Object.keys(files).length, bytes };
}

function entrySource(main) {
  return `// Generated by scripts/embed-assets.mjs: serves the app's static files from the Worker bundle.
import * as app from './${main}';
import { blobs, files, settings } from './embedded-assets.js';
export * from './${main}';

const worker = app.default;
const decoded = new Map();
function body(file) {
  let value = decoded.get(file.blob);
  if (!value) {
    const blob = blobs[file.blob];
    value = blob.text !== undefined ? new TextEncoder().encode(blob.text) : Uint8Array.from(atob(blob.base64), c => c.charCodeAt(0));
    decoded.set(file.blob, value);
  }
  return value;
}
const workerFirst = (pathname) => settings.workerFirst.some(p => p.endsWith('*') ? pathname.startsWith(p.slice(0, -1)) : pathname === p);
function lookup(pathname, req) {
  let name;
  try { name = decodeURIComponent(pathname); } catch { name = pathname; }
  if (files[name]) return files[name];
  if (name.endsWith('/') && files[name + 'index.html']) return files[name + 'index.html'];
  if (files[name + '.html']) return files[name + '.html'];
  // Single-page app: a page route (no file extension, or a browser asking for HTML) gets index.html.
  const page = !/\\.[A-Za-z0-9]+$/.test(name) || (req.headers.get('accept') || '').includes('text/html');
  if (settings.spa && page) return files['/index.html'];
  return null;
}
export function serveStatic(req) {
  const url = new URL(req.url);
  if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method Not Allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
  const file = lookup(url.pathname, req);
  if (!file) return new Response('Not Found', { status: 404 });
  const headers = { 'Content-Type': file.type, 'Cache-Control': file.cache, ETag: file.etag };
  if ((req.headers.get('if-none-match') || '').split(',').map(s => s.trim()).includes(file.etag)) return new Response(null, { status: 304, headers });
  return new Response(req.method === 'HEAD' ? null : body(file), { headers });
}

export default {
  ...worker,
  fetch(req, env, ctx) {
    if (workerFirst(new URL(req.url).pathname)) return worker.fetch(req, env, ctx);
    return serveStatic(req);
  },
};
`;
}
