/**
 * Builds the Sync to NKERP engine into one plain JavaScript file for the Vercel Functions in api/nkerp-sync/.
 * Vercel then runs plain JavaScript and never compiles the engine's TypeScript itself, so the Vite-oriented
 * tsconfig.json cannot break the deployment. Run after changing anything in server/nkerp-sync/:
 *   npm run build:api
 * The test suite fails if api/_lib/nkerp-sync.mjs is out of date.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const options = {
  entryPoints: [path.join(root, 'server/nkerp-sync/handlers.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  // Packages stay as normal imports from node_modules (Vercel traces them). undici is optional: only loaded
  // when an outbound proxy is configured.
  external: ['@google/genai', 'undici'],
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/nkerp-sync/. Do not edit; run `npm run build:api`.' },
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build({ ...options, outfile: path.join(root, 'api/_lib/nkerp-sync.mjs') });
  console.log('built api/_lib/nkerp-sync.mjs');
}
